export type TaskState = 'queued' | 'processing' | 'completed' | 'temporarily_unavailable' | 'failed' | 'insufficient_data';

export type ScanMode = 'image' | 'social_post' | 'message_scam' | 'video_frame' | 'link';

export interface LinkFinding {
  type: 'danger' | 'warning' | 'info';
  code: string;
  message: string;
}

export interface LinkScanResult {
  reportId?: string;
  url: string;
  normalizedUrl: string;
  protocol: string;
  hostname: string;
  riskLevel: 'safe' | 'suspicious' | 'dangerous';
  score: number; // 0 to 100 risk score (higher = riskier)
  summary: string;
  findings: LinkFinding[];
  domainChecks: {
    isPunycode: boolean;
    isIpHost: boolean;
    isShortener: boolean;
    hasSuspiciousKeywords: boolean;
    hasSensitiveParams: boolean;
    tld: string;
  };
  recommendations: string[];
  disclaimer: string;
}

export interface AuthUser {
  id: string;
  email: string;
  displayName: string;
  role: 'user' | 'admin';
  status: 'active' | 'disabled';
  createdAt?: string;
  lastLoginAt?: string | null;
}

export interface ForensicObservation {
  category: string;
  observation: string;
  severity: 'low' | 'medium' | 'high';
}

export interface ImageAuthenticitySection {
  status: 'suspicious' | 'inconclusive' | 'no_obvious_anomalies';
  statusLabel: string;
  confidenceLevel: 'low' | 'medium' | 'high';
  observations: ForensicObservation[];
  technicalNote: string;
}

export interface ScamRiskSection {
  detected: boolean;
  riskLevel: 'low' | 'medium' | 'high';
  title: string;
  deceptiveTactics: string[];
  exactQuotes: string[];
  explanation: string;
}

export interface ImpersonationRiskSection {
  detected: boolean;
  riskLevel: 'low' | 'medium' | 'high';
  suspiciousIndicators: string[];
  accountVerificationNeeds: string[];
  explanation: string;
}

export interface PersonalSafetyRiskSection {
  detected: boolean;
  riskLevel: 'low' | 'medium' | 'high';
  riskTypes: ('bullying' | 'blackmail' | 'privacy_breach' | 'financial_loss' | 'psychological_pressure' | 'misinformation')[];
  safetyGuidance: string;
  emergencyNotice?: string;
}

export interface SourcesAndEvidenceSection {
  extractedOcrText?: string;
  analyzedLinks: Array<{
    url: string;
    warning: string;
    isDeceptiveOrShortened: boolean;
  }>;
  unverifiedGaps: string[];
  intelligenceReferences?: Array<{ title: string; url: string }>;
}

export interface ActionGuidanceSection {
  step1Stop: string;
  step2Verify: string[];
  step3Protect: string[];
  step4GetHelp: string[];
}

export interface ThreatScanResult {
  reportId?: string;
  analyzedAt?: string;
  taskState?: TaskState;
  scanMode: ScanMode;
  /** True when results were generated by text heuristics rather than Gemini. */
  isHeuristicNotice?: boolean;
  engineUsed?: 'gemini' | 'openrouter' | 'openai' | 'deepseek' | 'heuristic';
  modelUsed?: string;
  processingDurationMs?: number;
  overallStatus: 'suspicious' | 'inconclusive' | 'no_obvious_anomalies' | 'insufficient_data';
  overallStatusLabel: string;
  summary: string;
  matchedScenarioCodes: string[]; // e.g. ['SCENARIO_1_CELEB_SCAM', 'SCENARIO_6_OTP_THEFT']
  imageAuthenticity: ImageAuthenticitySection;
  scamRisks: ScamRiskSection;
  impersonationRisks: ImpersonationRiskSection;
  personalSafetyRisks: PersonalSafetyRiskSection;
  sourcesAndEvidence: SourcesAndEvidenceSection;
  actionGuidance: ActionGuidanceSection;
  scientificDisclaimer: string;
  limitations?: string[];
  verificationGuidance?: string[];
}

// Backward-compatible alias for existing components
export type ScanResult = ThreatScanResult;

