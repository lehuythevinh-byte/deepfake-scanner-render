export type ScanMode = 'image' | 'social_post' | 'message_scam';

export interface AppUser {
  id: string;
  email: string;
  displayName: string;
  role: 'user' | 'admin';
  status: 'active' | 'suspended';
  createdAt?: string;
  lastLoginAt?: string | null;
}


export interface ForensicObservation {
  category: string;
  observation: string;
  severity: 'low' | 'medium' | 'high';
}

export interface ImageAuthenticitySection {
  status: 'suspicious' | 'inconclusive' | 'no_obvious_anomalies';
  statusLabel: string;
  confidenceLevel: 'low' | 'medium' | 'high';
  observations: ForensicObservation[];
  technicalNote: string;
}

export interface ScamRiskSection {
  detected: boolean;
  riskLevel: 'low' | 'medium' | 'high';
  title: string;
  deceptiveTactics: string[];
  exactQuotes: string[];
  explanation: string;
}

export interface ImpersonationRiskSection {
  detected: boolean;
  riskLevel: 'low' | 'medium' | 'high';
  suspiciousIndicators: string[];
  accountVerificationNeeds: string[];
  explanation: string;
}

export interface YouthRiskSection {
  detected: boolean;
  riskLevel: 'low' | 'medium' | 'high';
  riskTypes: ('bullying' | 'blackmail' | 'privacy_breach' | 'financial_loss' | 'psychological_pressure' | 'misinformation')[];
  studentGuidance: string;
  emergencyNotice?: string;
}

export interface SourcesAndEvidenceSection {
  extractedOcrText?: string;
  analyzedLinks: Array<{
    url: string;
    warning: string;
    isDeceptiveOrShortened: boolean;
  }>;
  unverifiedGaps: string[];
}

export interface ActionGuidanceSection {
  step1Stop: string;
  step2Verify: string[];
  step3Protect: string[];
  step4Report: string[];
}

export interface ThreatScanResult {
  scanMode: ScanMode;
  /** True when results were generated by text heuristics rather than Gemini. */
  isHeuristicNotice?: boolean;
  /** Safe diagnostic code returned when Gemini failed and the scanner used heuristics. */
  aiFailureCode?: string;
  overallStatus: 'suspicious' | 'inconclusive' | 'no_obvious_anomalies';
  overallStatusLabel: string;
  summary: string;
  matchedScenarioCodes: string[]; // e.g. ['SCENARIO_1_CELEB_SCAM', 'SCENARIO_6_OTP_THEFT']
  imageAuthenticity: ImageAuthenticitySection;
  scamRisks: ScamRiskSection;
  impersonationRisks: ImpersonationRiskSection;
  youthRisks: YouthRiskSection;
  sourcesAndEvidence: SourcesAndEvidenceSection;
  actionGuidance: ActionGuidanceSection;
  scientificDisclaimer: string;
}

